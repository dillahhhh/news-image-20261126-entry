// Width of a string at cap height capH (pixels). y is the cap-top.
export function serifWidth(s, capH) {
  const u = capH / 10;
  let w = 0;
  for (const ch of s) {
    const gl = SERIF[ch] || SERIF['?'];
    w += gl[0] * u;
  }
  return w - 0.9 * u;
}

// Draw string s with cap-top at (x, y). wtMul scales stroke weight
// (1 = regular, ~1.25 = bold). Returns the x after the last glyph.
export function drawSerif(g, x, y, s, capH, c, wtMul) {
  const u = capH / 10;
  const wm = wtMul || 1;
  let cx = x;
  for (const ch of s) {
    const gl = SERIF[ch] || SERIF['?'];
    for (let i = 1; i < gl.length; i++) {
      const st = gl[i];
      const w = Math.max(1, Math.round(st[0] * u * wm));
      for (let p = 1; p + 3 < st.length; p += 2) {
        g.line(
          Math.round(cx + st[p] * u), Math.round(y + st[p + 1] * u),
          Math.round(cx + st[p + 2] * u), Math.round(y + st[p + 3] * u),
          c, w
        );
      }
    }
    cx += gl[0] * u;
  }
  return cx;
}

// Word-wrap plain text to a pixel width at cap height capH.
export function wrapSerif(s, maxW, capH) {
  const words = s.split(' ');
  const lines = [];
  let cur = '';
  for (const w of words) {
    const trial = cur ? cur + ' ' + w : w;
    if (serifWidth(trial, capH) <= maxW || !cur) {
      cur = trial;
    } else {
      lines.push(cur);
      cur = w;
    }
  }
  if (cur) lines.push(cur);
  return lines;
}
